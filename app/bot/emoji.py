def button(
    text: str,
    callback_data: str,
    emoji_number: int,
    *,
    style: str | None = None,
) -> InlineKeyboardButton:
    """Use native button colours and Unicode icons (no Premium requirement)."""
    if style is None:
        if text.startswith(
            (
                "Удалить",
                "Подтвердить удаление",
                "Остановить",
                "Отключить",
                "Пауза",
                "Приостановить",
                "Убрать",
                "Отписать",
            )
        ):
            style = "danger"
        elif text.startswith(
            (
                "Добавить",
                "Запустить",
                "Начать",
                "Продолжить",
                "Применить",
                "Подтвердить",
                "Включить",
                "Возобновить",
                "Назначить",
                "Сохранить",
                "Подписать",
            )
        ):
            style = "success"
        elif callback_data in {"menu:work", "own:add"} or text.startswith(
            ("Проверить", "Скачать", "Загрузить")
        ):
            style = "primary"
    icon = BUTTON_EMOJI[emoji_number][0] if emoji_number != 83 else ""
    return InlineKeyboardButton(
        text=f"{icon} {text}" if icon else text,
        callback_data=callback_data,
        style=style,
    )


def animated(emoji_number: int) -> str:
    """Return an HTML custom-emoji entity with a Unicode fallback."""
    fallback, emoji_id = MESSAGE_EMOJI[emoji_number]
    return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'
